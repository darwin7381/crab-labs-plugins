#!/usr/bin/env python3
"""Regenerate fleet-text.ts from the spec's #text card (Chiron owns the words; change them there).

Usage: python3 tools/gen-fleet-text.py ~/rescue-site/inbox-tiers.html
Writes ../fleet-text.ts next to server.ts. h3 → a line, p → a paragraph, li → "- " item, inline tags dropped.
"""
import html, json, os, re, subprocess, sys

src = sys.argv[1]
s = open(src, encoding="utf-8").read()
i = s.index('id="text"')
card = s[s.index('<div class="card">', i):s.index('id="aid"')]
card = card[:card.rindex("</div>")]
out = []
for m in re.finditer(r"<(h3|p|li)\b[^>]*>(.*?)</\1>", card, re.S):
    tag, inner = m.group(1), m.group(2)
    t = html.unescape(re.sub(r"<[^>]+>", "", inner)).strip()
    t = re.sub(r"\s+", " ", t)
    out.append(("- " if tag == "li" else "") + t)
# paragraphs/headings separated by a blank line; consecutive list items by a single newline
text = ""
prev = None
for line in out:
    li = line.startswith("- ")
    if prev is not None:
        text += "\n" if (li and prev) else "\n\n"
    text += line
    prev = li
try:
    rev = subprocess.run(["git", "-C", os.path.dirname(os.path.abspath(src)), "log", "-1", "--format=%h", "--", os.path.basename(src)],
                         capture_output=True, text=True).stdout.strip()
except Exception:
    rev = "?"
dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "fleet-text.ts")
with open(dst, "w", encoding="utf-8") as f:
    f.write("// GENERATED by tools/gen-fleet-text.py from rescue-site inbox-tiers.html #text"
            f" (rev {rev}). Do not edit here: the words are Chiron's (WO-91) — change the spec, then regenerate.\n")
    f.write(f"export const FLEET_TEXT = {json.dumps(text, ensure_ascii=False)}\n")
print(f"{len(text)} chars → {os.path.normpath(dst)} (rev {rev})")
