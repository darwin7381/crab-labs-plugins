// Universe 002l (N7, RV2 T8-R #10): a turn cut right after the main took in a channel message is a cut turn, so a deliberate restart is recognised.
// 002j: 「有人下令重啟的，不再叫它接著做」. Transcript shapes as this Claude Code writes them (channel deliveries are user records with isMeta:true).
import { test, expect } from 'bun:test'
import { mkdtempSync, writeFileSync } from 'fs'
import { tmpdir } from 'os'
import { join } from 'path'
import { cutOffTurn, resumeDecision } from './lanes.ts'
const dir = mkdtempSync(join(tmpdir(), 'lanes-n7-'))
const rec = (o: object) => JSON.stringify(o) + '\n'
const done = rec({ type: 'assistant', timestamp: '2026-11-15T02:00:00.000Z', message: { model: 'claude-haiku-5-5', stop_reason: 'end_turn', content: [{ type: 'text', text: '好' }] } }) + rec({ type: 'system', subtype: 'turn_duration' })
const channel = rec({ type: 'user', isMeta: true, timestamp: '2026-11-15T02:04:58.000Z', message: { role: 'user', content: '<channel source="plugin:telegram-http:telegram-http" chat_id="1" message_id="1012" user="joey_lab">\n/restart 然後把報告做完\n</channel>' } })
const apiReq = rec({ type: 'api-request-shape', sessionId: 's', shapeHash: 'h', timestamp: '2026-11-15T02:04:58.100Z' })
const resumed = rec({ type: 'assistant', timestamp: '2026-11-15T02:05:10.000Z', message: { model: '<synthetic>', stop_reason: 'stop_sequence', content: [{ type: 'text', text: 'No response requested.' }] } })

test('N7: the main took in a channel message (isMeta), an API request went out, then it was killed: the turn was cut', () => {
  const p = join(dir, 'k4.jsonl')
  writeFileSync(p, done + channel + apiReq + resumed)
  expect(cutOffTurn(p)).toEqual({ cut: true, at: '2026-11-15T02:04:58.000Z' })
  expect(resumeDecision(cutOffTurn(p), true, null)).toBe('deliberate')                // the asked-for restart is seen
  expect(resumeDecision(cutOffTurn(p), false, null)).toBe('notice')
})

test('N7: other meta user records (reminders, hook companions) still open no turn', () => {
  const p = join(dir, 'meta.jsonl')
  writeFileSync(p, done + rec({ type: 'user', isMeta: true, timestamp: 't', message: { role: 'user', content: '<system-reminder><tools-used-before-summary>…</tools-used-before-summary></system-reminder>' } }) + resumed)
  expect(cutOffTurn(p).cut).toBe(false)
  writeFileSync(p, done + rec({ type: 'user', isMeta: true, timestamp: 't', message: { role: 'user', content: [{ type: 'text', text: 'Caveat: the messages below were generated by the user while running local commands.' }] } }) + resumed)
  expect(cutOffTurn(p).cut).toBe(false)
})
